#!/usr/bin/env python3
"""Build `tools/opi_verify.py`: the whole validator as one stdlib-only file.

The package is written so that `jcs.py`, `ed25519.py`, `container.py`,
`sign.py` and `validate.py` together *are* the validator and depend on
nothing outside the standard library. This script concatenates them into
a single file that can be copied next to a shell script, pasted into a CI
job, or handed to a MAM vendor — no install, no import path.

Deterministic: the same sources produce the same bundle byte for byte, and
`tests/test_bundle.py` fails if the checked-in bundle drifts from the
sources. Run it after any change to those five modules:

    python tools/build_bundle.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "openpicture"
OUT = ROOT / "tools" / "opi_verify.py"

# Order matters: each module may only reference the ones before it.
MODULES = ("jcs", "ed25519", "container", "sign", "time", "runs", "embeddings", "keyframes", "members", "facets", "validate")

_FUTURE = re.compile(r"^from __future__ import annotations\n", re.M)
_REL_IMPORT = re.compile(r"^from \. import [^\n]+\n", re.M)

HEADER = '''\
#!/usr/bin/env python3
"""opi_verify — validate `.opi` (Open Picture Intelligence) files. One file, no dependencies.

    python3 opi_verify.py clip.mov.opi [more.opi ...]     exit 0 = every file valid
    python3 opi_verify.py --json clip.mov.opi              machine-readable report
    python3 opi_verify.py --media-dir /vol/footage clip.mov.opi

Checks the envelope, the media binding (sha256 of the master when it is
beside the sidecar), Full-container members and their 64-byte alignment,
and every producer run's Ed25519 signature over RFC 8785 canonical JSON.
Reports per run. "unsigned" is valid; "invalid" is not.

GENERATED by tools/build_bundle.py from the openpicture package — do not
edit by hand; edit the package and rebuild. Standard library only, by
design, so this file can be copied anywhere Python 3.11+ runs.
Format specification: SPEC.md in the openpicture repository.
"""

from __future__ import annotations

import argparse
import json
import sys

MANIFEST_MEMBER = "manifest.json"
ALIGNMENT = 64

'''

MODULE_BANNER = "\n# {rule}\n# openpicture/{name}.py\n# {rule}\n\n"

NAMESPACE = '''
{name} = _Namespace(**{{_n: globals()[_n] for _n in __all__}})
'''

PRELUDE = '''
class _Namespace:
    """Stands in for the `openpicture.<module>` namespaces the sources refer to."""

    def __init__(self, **items):
        self.__dict__.update(items)

'''

MAIN = '''

# ─────────────────────────────────────────────────────────────────────
# entry point
# ─────────────────────────────────────────────────────────────────────


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="opi_verify", description=__doc__.splitlines()[1].strip())
    ap.add_argument("path", nargs="+", help=".opi file(s) to validate")
    ap.add_argument("--media-dir", help="where to look for the bound media (default: beside each sidecar)")
    ap.add_argument("--json", action="store_true", help="machine-readable report")
    args = ap.parse_args(argv)
    worst = 0
    for path in args.path:
        report = validate(path, media_dir=args.media_dir)
        if args.json:
            print(json.dumps(report.as_dict(), indent=2))
        else:
            print(f"{report.status:14} {path}  (profile={report.profile}, opi={report.version}, signatures={report.signature_status})")
            for c in report.checks:
                if not c.ok or c.detail:
                    print(f"  {'ok  ' if c.ok else 'FAIL'} {c.name}: {c.detail}")
        if not report.ok:
            worst = 1
    return worst


if __name__ == "__main__":
    sys.exit(main())
'''


def module_body(name: str) -> str:
    src = (PKG / f"{name}.py").read_text(encoding="utf-8")
    src = _FUTURE.sub("", src)
    src = _REL_IMPORT.sub("", src)
    # `container.py` reads the constant from the package; the bundle defines
    # it at the top, and the same for ALIGNMENT which validate.py reaches
    # through `container.ALIGNMENT` (kept working by the namespace object).
    return src.rstrip("\n") + "\n"


def build() -> str:
    rule = "─" * 69
    parts = [HEADER, PRELUDE]
    for name in MODULES:
        parts.append(MODULE_BANNER.format(rule=rule, name=name))
        parts.append(module_body(name))
        if name != MODULES[-1]:  # the last module's names are the bundle's own
            parts.append(NAMESPACE.format(name=name))
    parts.append(MAIN)
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = build()
    if argv[:1] == ["--check"]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run tools/build_bundle.py", file=sys.stderr)
            return 1
        print("bundle up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    OUT.chmod(0o755)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.encode()):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
